import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { agendaBandosItems } from '../src/data/agenda-bandos.generated.ts';
import { buildAgendaProjection, parseBandoMarkdown } from './agenda-from-bandos.ts';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, '..');
const bandosDirectory = path.join(projectRoot, 'src', 'content', 'bandos');
const generatedFile = path.join(projectRoot, 'src', 'data', 'agenda-bandos.generated.ts');

async function loadBandosMarkdown(): Promise<string[]> {
  const entries = await fs.readdir(bandosDirectory, { withFileTypes: true });
  const files = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right, 'es'));
  return Promise.all(files.map((file) => fs.readFile(path.join(bandosDirectory, file), 'utf8')));
}

function countParsedSources(markdown: readonly string[]): { parsed: number; eligible: number } {
  let parsed = 0;
  let eligible = 0;
  for (const entry of markdown) {
    const source = parseBandoMarkdown(entry);
    if (!source) continue;
    parsed += 1;
    if (buildAgendaProjection([entry]).length > 0) eligible += 1;
  }
  return { parsed, eligible };
}

async function renderGeneratedModule(
  items: ReturnType<typeof buildAgendaProjection>,
): Promise<string> {
  const source = [
    '/* Generated by scripts/sync-agenda-from-bandos.ts; edit the source Bando or agenda-manual.ts. */',
    "import type { AgendaItem } from './current-affairs';",
    '',
    `export const agendaBandosItems: AgendaItem[] = ${JSON.stringify(items, null, 2)};`,
    '',
  ].join('\n');
  const config = (await prettier.resolveConfig(generatedFile)) ?? {};
  return prettier.format(source, { ...config, filepath: generatedFile });
}

export async function syncAgendaFromBandos(): Promise<{
  changed: boolean;
  bandoFiles: number;
  parsedSources: number;
  eligibleSources: number;
  agendaItems: number;
}> {
  const markdown = await loadBandosMarkdown();
  const counts = countParsedSources(markdown);
  const items = buildAgendaProjection(markdown, agendaBandosItems);
  const rendered = await renderGeneratedModule(items);
  const previous = await fs.readFile(generatedFile, 'utf8');
  const changed = previous !== rendered;
  if (changed) await fs.writeFile(generatedFile, rendered, 'utf8');
  return {
    changed,
    bandoFiles: markdown.length,
    parsedSources: counts.parsed,
    eligibleSources: counts.eligible,
    agendaItems: items.length,
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = await syncAgendaFromBandos();
    console.log(
      `Agenda de bandos: ${result.bandoFiles} comunicados leídos, ${result.parsedSources} fuentes válidas, ${result.eligibleSources} con fechas elegibles y ${result.agendaItems} entradas conservadas; ${result.changed ? 'proyección actualizada' : 'sin cambios'}.`,
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
